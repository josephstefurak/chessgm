"""Generate tools/openings.txt: short, balanced, varied opening lines for matches.

One-off script; the output file is committed so matches are reproducible.
Each line is built by picking, at every ply, a random move among Stockfish's top
choices (within 40cp of the best), then kept only if the final position is within
50cp of equal. This gives natural-looking openings without relying on either
engine's own opening book.

Usage:
    python tools/make_openings.py /path/to/stockfish
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import chess
import chess.engine

PLIES = 6
COUNT = 60
SEED = 20261113
PICK_MARGIN_CP = 40
BALANCE_CP = 50


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    rng = random.Random(SEED)
    lines: list[str] = []
    seen: set[str] = set()
    engine = chess.engine.SimpleEngine.popen_uci(argv[1])
    try:
        while len(lines) < COUNT:
            board = chess.Board()
            for _ in range(PLIES):
                infos = engine.analyse(board, chess.engine.Limit(depth=8), multipv=4)
                best = infos[0]["score"].relative.score(mate_score=10000)
                choices = [
                    info["pv"][0]
                    for info in infos
                    if best - info["score"].relative.score(mate_score=10000) <= PICK_MARGIN_CP
                ]
                board.push(rng.choice(choices))
            final = engine.analyse(board, chess.engine.Limit(depth=12))
            score = final["score"].white().score(mate_score=10000)
            line = " ".join(move.uci() for move in board.move_stack)
            if abs(score) <= BALANCE_CP and line not in seen:
                seen.add(line)
                lines.append(line)
    finally:
        engine.quit()

    header = (
        "# Balanced opening lines for tools/match.py. Generated by tools/make_openings.py\n"
        f"# (seed {SEED}, {PLIES} plies, final Stockfish eval within {BALANCE_CP}cp of equal).\n"
    )
    out = Path(__file__).resolve().parent / "openings.txt"
    out.write_text(header + "\n".join(lines) + "\n")
    print(f"wrote {len(lines)} openings to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
